using System;

namespace Ecomerce_dotnet.Models
{
    public class Payment
    {
        public Guid Id { get; set; } = Guid.NewGuid();

        public string Invoice { get; set; } = string.Empty; // e.g. "INV-20260731112500123"
        public decimal Amount { get; set; }
        public string Currency { get; set; } = "USD";
        public string Md5 { get; set; } = string.Empty; // generated by Bakong SDK
        public string QrString { get; set; } = string.Empty; // EMVCo KHQR string
        public string Status { get; set; } = "PENDING"; // PENDING, PAID, FAILED

        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
        public DateTime? PaidAt { get; set; }

        public Guid? OrderId { get; set; }
        public Order? Order { get; set; }

        public string BakongTransactionRef { get; set; } = string.Empty; // Holds Bakong Hash
        public string? FromAccountId { get; set; }
        public string? ToAccountId { get; set; }
        public string? Description { get; set; }
    }
}
